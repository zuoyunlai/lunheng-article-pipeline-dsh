// 数据信任级别口径（全流水线唯一真源）
//
// 三档（顺序即优先级）：主人投喂 > 二手转引 > 已发布。
// 语义：M-Form-6 / M-Exist-3 要求每条 [Dxx] 有**独立**「信任级别：<档>」行。
// 历史教训：`normalize-trust-level.mjs` 旧版在卡内无 token 时**默认填「已发布」**（最高档），
// 让 M-Form-6 机械判过 —— 证据链污染。现该脚本改为**拒绝推断**（见其头部注释）。

/** 三档取值（顺序即优先级）。 */
export const TRUST_TOKENS = ['主人投喂', '二手转引', '已发布']

/** 合规独立行：`信任级别：<档>（备注）`。
 *  v18.2.6 修（第三方审计 P2「normalize-trust-level 对加粗形态重复插入」的根因之一）：
 *  旧式 `/信任级别\**[:：]\s*(…)` 只容忍**冒号前**的星号，遇到手写常见的
 *  `信任级别：**已发布**`（加粗**档位词**）即失配 → 该行被判「无信任级别」→
 *  ① `normalize-trust-level.mjs` **重复插入**第二条 `信任级别：已发布`；
 *  ② M-Form-6 把已有独立行的条目误判为「独立段缺失」。
 *  现容许冒号两侧的 `*`/空白（含全角空格）。**不跨行**（`[ \t\u3000]` 而非 `\s`，
 *  否则「信任级别：」行尾的换行会让下一行的档位词被算作本行声明）。 */
export const TRUST_COMPLIANT_RE = /信任级别\**[ \t\u3000]*[:：][ \t\u3000]*\**[ \t\u3000]*(已发布|主人投喂|二手转引)/

/** 宽松判定（M-Form-6 双格式：描述字段里含信任级别字样或档位词即可）。
 *
 *  v18.2.6 修（第三方审计 P1-4）：旧版写作 `/信任级别\**[:：]|\b已发布\b|\b主人投喂\b|\b二手转引\b/`
 *  —— JS 的 `\b` 以 `\w`（即 `[A-Za-z0-9_]`）为界，而**汉字不属于 `\w`**，故 `\b` 在「为」与「已」
 *  之间、在字符串开头与「主」之间**都不成立**。实测旧版：
 *    · `该数据为已发布状态` → **false**（`为|已` 之间无边界）
 *    · `来源为二手转引`     → **false**
 *    · `主人投喂`（独立成句）→ **false**（串首无 `\b`）
 *    · `a已发布b` / `信任级别：已发布` → true（拉丁字母/冒号侧的 `\b` 恰好成立）
 *  后果（使用点 `m-gate-check.mjs:480→:498`）：M-Form-6 的「描述字段仅有」**降级路径基本不可达**，
 *  真实稿件里 `信任级别` 只写在描述句中的数据条目一律落进 `trustLevelMiss`，>5 条即判 P0 ——
 *  即「用拉丁语系的词边界规则判中文」。汉语无词边界，`\b` 在此既无必要也不正确 → **直接去掉边界断言**。
 *  （宽松档只影响 M-Form-6 的 P2 降级路径与 `pickTrustToken` 的兜底，不改变硬判 `TRUST_COMPLIANT_RE`。） */
export const TRUST_LOOSE_RE = /信任级别\**[:：]|已发布|主人投喂|二手转引/

/** 从卡片切块里挑出档位 token；**无 token 返回 undefined**（调用方必须自己决定如何处理，
 *  不得默认填最高档）。
 *
 *  v18.2.6 修（第三方审计 P1-4 后半）：旧实现 `TRUST_TOKENS.find(t => block.includes(t))` 对**整块**
 *  做 includes、并按数组顺序取首个命中 —— 实测把「信任级别：已发布（备注：本文二手转引自某日报）」
 *  判成 **二手转引**（备注里的档位词**污染**了独立行的档位，而 二手转引 在 TRUST_TOKENS 里排在 已发布 之前）。
 *  规则改为：
 *    ① 存在「信任级别」行 → 取**紧跟该行冒号的那一档**（走 `TRUST_COMPLIANT_RE`，备注里再出现别的档位词也不影响）；
 *    ② 该行存在但冒号后没写档位（如 `信任级别：待定`）、或整块**无独立行**（描述字段仅有档位词的降级场景）
 *       → 保留旧的全块兜底口径（`normalize-trust-level.mjs` 的「描述里写了档位、缺独立行 → 据此补独立行」
 *       正是靠这一档工作；见其回归用例「摘要：本数据二手转引自某日报」）。 */
export const pickTrustToken = (block) => {
  const s = String(block ?? '')
  const line = s.split(/\r?\n/).find((l) => /信任级别\**[:：]/.test(l))
  if (line !== undefined) {
    const onLine = TRUST_COMPLIANT_RE.exec(line)   // 只看紧跟冒号的那一档
    if (onLine) return onLine[1]
  }
  return TRUST_TOKENS.find((t) => s.includes(t))
}
