/** 从期刊数据库的**表行**数派生规模（表格行 ≠ 表头 ≠ 分隔行）。 */
export function deriveJournalCounts(dbText) {
  const lines = dbText.split('\n')
  let sec = null
  const counts = {}
  for (const l of lines) {
    const h = l.match(/^##\s+([一二三四五六七八九十]+)、(.+)$/)
    if (h) { sec = h[2].trim(); counts[sec] = 0; continue }
    if (!sec) continue
    if (/^\|/.test(l) && !/^\|[\s:|-]+\|$/.test(l)) counts[sec]++
  }
  const pick = (kw) => {
    const k = Object.keys(counts).find((x) => x.includes(kw))
    return k ? counts[k] - 1 : null // 扣掉表头行
  }
  return { zh: pick('中文'), en: pick('英文') }
}

/** 从章节标题里读真源**自称**的规模（形如 `## 一、中文期刊（CSSCI/北大核心，28 个）` / `## 二、英文 SSCI 期刊（12 个）`）。 */
export function declaredJournalCounts(dbText) {
  const g = (kw) => {
    for (const l of dbText.split('\n')) {
      if (l.startsWith('##') && l.includes(kw)) {
        // 注意逗号是**可选**的：中文那节写「（CSSCI/北大核心，28 个）」，英文那节写「（12 个）」。
        // 第一版把逗号写成必需的，英文侧直接 null → 误报「解析器脱节」。
        const m = l.match(/，?\s*(\d+)\s*个/)
        if (m) return Number(m[1])
      }
    }
    return null
  }
  return { zh: g('中文'), en: g('英文') }
}

