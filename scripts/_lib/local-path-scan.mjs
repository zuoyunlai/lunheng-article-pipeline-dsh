// 本机绝对路径扫描（D-2·修法② · v18.18.4）——供 `repo-hygiene-check` 规则⑦ 使用，可单测。
//
// ── 为什么需要 ────────────────────────────────────────────────────────
// 审计 D-2 实测：发布物里含作者本机绝对路径——`references/glossary.md`、
// `M-Gate-Algorithm.md`、`mintegrity-gate.mjs` 三处写着 `E:\<本机根>\…`，其中一处
// 还带**内部项目目录名**与**内部审计报告名**。当时的对照门输出却是
// 「✓ ⑦ 凭据扫描：212 个文本文件 × 10 类模式，无命中」——**规则⑦ 只扫凭据形态**，
// 对「路径」这一类可避免的信息泄露完全无感。
//
// 三处内容本身已在早前批次改为占位符（`<项目根>/run/审计/<内部报告名>.md` 等），
// 本模块补的是**防复发的那一半**：没有门，下次有人再写一条真实路径，没人会发现。
//
// ── 模式设计原则（这是一次返工的结论）────────────────────────────────
// **只认真正指向某台具体机器 / 某个具体人的路径。**
// 第一版把 `C:\repo` / `D:\data\x.xlsx` 这类**示例占位**也算进去了，结果门一上来就红，
// 而红的原因是文档在教读者「把这里换成你自己的路径」——那是正当写法。
// 一个会被正当写法触发的门，结局只有一个：被关掉。故：
//   · `C:\Users\<用户>\…` 放行（尖括号 = 占位）
//   · `C:\Users\Zuoyunlai\…` 命中（真实用户名）
//   · `C:\repo` / `D:\data` 放行（通用示例，非机器指纹）
//   · `E:\HERNESS\…` 命中（本仓库作者的真实工作根，属机器指纹）
//
// ── 边界（如实）────────────────────────────────────────────────────
// · **不能回溯**：这些字符串**已在 git 历史与 GitHub 上**。清理工作区不能让它们消失，
//   真要撤回须改写历史 + force push（破坏性，且须主人决定）。本模块只能挡住**新的**。
// · 用户名 `Zuoyunlai` 本身**已是公开信息**（`package.json` 的 `author` + GitHub 用户名），
//   故 `C:\Users\Zuoyunlai\` 的**边际**泄露接近于零；真正值得在意的是内部项目/报告命名。
// · 模式是**启发式**，不追求完备——它挡的是本仓库实际出现过的那几类形态。

/** 占位写法：出现这些「用户名」说明是在教读者填自己的值，不是在泄露。 */
export const PLACEHOLDER_NAMES = new Set(['用户', '你', '您', 'user', 'username', 'name', 'USER', 'USERNAME'])

export const LOCAL_PATH_PATTERNS = [
  {
    id: 'win-user-home',
    re: /[A-Za-z]:\\{1,2}Users\\{1,2}([^\\/\s`'"<>)\]]+)/g,
    why: 'Windows 用户目录（含真实用户名）',
  },
  { id: 'posix-home', re: /\/home\/([a-z][a-z0-9_-]*)\//g, why: 'POSIX 家目录（含真实用户名）' },
  { id: 'mac-home', re: /\/Users\/([a-z][a-z0-9_-]*)\//g, why: 'macOS 家目录（含真实用户名）' },
  { id: 'machine-root', re: /[A-Za-z]:\\{1,2}HERNESS\\{1,2}/g, why: '作者本机工作根（机器指纹）' },
  {
    id: 'backup-dir',
    re: /_backup\\{1,2}lunheng-[0-9a-zA-Z-]+/g,
    why: '作者本机备份目录（含日期，机器指纹）',
  },
]

/**
 * 扫一段文本里的本机绝对路径。
 * @param {string} text
 * @returns {{id:string,text:string,why:string}[]}
 */
export function scanLocalPaths(text) {
  const out = []
  for (const p of LOCAL_PATH_PATTERNS) {
    for (const m of text.matchAll(p.re)) {
      if (m[1] && PLACEHOLDER_NAMES.has(m[1])) continue // `<用户>` 这类占位放行
      out.push({ id: p.id, text: m[0], why: p.why })
    }
  }
  return out
}

